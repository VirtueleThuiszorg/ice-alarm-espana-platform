#!/usr/bin/env node
/**
 * ROUTE PATH -> THE MODULE THAT RENDERS IT, generated from App.tsx.
 *
 * `usePrefetchRoute` needs to start downloading a route's chunk when a person
 * hovers the link that leads there. To do that it needs the same `import()` the
 * router will eventually call — the SAME specifier, or Vite resolves it to a
 * different module and the prefetch warms a chunk nobody asks for.
 *
 * Hand-maintaining 113 importers beside the 113 already in App.tsx is the
 * "duplicate parallel implementation" CLAUDE.md forbids, and it would rot the
 * first time somebody added a page. So this parses App.tsx and joins two facts
 * it already states:
 *
 *   const MembersPage = lazyWithRetry(() => import("./pages/admin/MembersPage"))
 *   <Route path="/admin/members" element={<MembersPage />} />
 *
 * and writes src/lib/routeModules.generated.ts.
 *
 *   node scripts/routes/build-prefetch-map.mjs          # write
 *   node scripts/routes/build-prefetch-map.mjs --check  # fail if stale
 *
 * The --check form runs in src/test/perf/prefetch.test.ts, so adding a route
 * without regenerating fails CI rather than silently leaving that link
 * un-prefetched.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const APP = path.join(ROOT, "src/App.tsx");
const OUT = path.join(ROOT, "src/lib/routeModules.generated.ts");

export function buildMap() {
  const src = fs.readFileSync(APP, "utf8");

  // component name -> import specifier
  const byComponent = new Map();
  for (const m of src.matchAll(
    /const (\w+) = lazyWithRetry\(\s*\(\)\s*=>\s*import\("([^"]+)"\)/gs,
  )) {
    byComponent.set(m[1], m[2]);
  }

  /*
    ROUTES NEST, and the first version of this did not know that.

    The admin and call-centre surfaces are declared as children of a layout
    route:

        <Route path="/admin" element={<AdminLayout />}>
          <Route path="products" element={<ProductCatalogPage />} />

    Matching only `path="..."` with a leading slash found 80 routes and silently
    missed every nested one — including every page a staff sidebar links to,
    which is most of what there is to prefetch. So this walks the <Route> tags in
    order, keeping a stack of the open ones, and joins the segments.
  */
  const routes = new Map();
  const stack = [];
  const TAG = /<Route\b([^>]*?)(\/?)>|<\/Route>/g;

  for (const tag of src.matchAll(TAG)) {
    if (tag[0] === "</Route>") {
      stack.pop();
      continue;
    }
    const attrs = tag[1] ?? "";
    const selfClosing = tag[2] === "/";
    const pathAttr = /\bpath="([^"]*)"/.exec(attrs)?.[1];
    const element = /\belement=\{<(\w+)/.exec(attrs)?.[1];

    const segment = pathAttr ?? "";
    const full = segment.startsWith("/")
      ? segment
      : `${stack.join("/")}/${segment}`.replace(/\/{2,}/g, "/").replace(/\/$/, "") || "/";

    if (!selfClosing) stack.push(full === "/" ? "" : full);

    if (!element) continue;
    const specifier = byComponent.get(element);
    if (!specifier) continue;
    const routePath = full;
    // A parameterised path cannot be prefetched from a nav link — the link
    // carries a concrete id and the router matches the pattern. Nav items point
    // at static paths, so those are the ones worth warming.
    if (routePath.includes(":") || routePath.includes("*")) continue;
    /*
      REWRITTEN THROUGH THE ALIAS. The specifier is relative to App.tsx
      ("./pages/Index"), and the generated file lives in src/lib/, where that
      resolves to nothing. `@/` is Vite's alias for /src/, so "@/pages/Index" and
      App.tsx's "./pages/Index" resolve to the SAME module id — which is what
      makes them the same chunk. A prefetch that warmed a different chunk would
      be pure cost.
    */
    routes.set(routePath, specifier.replace(/^\.\//, "@/"));
  }

  return routes;
}

const routes = buildMap();
const entries = [...routes.entries()].sort(([a], [b]) => a.localeCompare(b));

const serialised = `/* GENERATED by scripts/routes/build-prefetch-map.mjs — do not edit.
 *
 * Route path -> the dynamic import that renders it, lifted from App.tsx so the
 * specifiers are identical. \`usePrefetchRoute\` calls these on hover/focus/touch
 * so the chunk is already in the browser's cache when the click lands.
 *
 * Parameterised and wildcard routes are omitted: a nav link points at a static
 * path, and warming a pattern is not something the browser can do.
 */
export const ROUTE_MODULES: Record<string, () => Promise<unknown>> = {
${entries.map(([p, spec]) => `  ${JSON.stringify(p)}: () => import(${JSON.stringify(spec)}),`).join("\n")}
};

/** How many routes the generator found, asserted in the test so a parse break is loud. */
export const ROUTE_MODULE_COUNT = ${entries.length};
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== serialised) {
    console.error(
      "src/lib/routeModules.generated.ts is stale.\n" +
        "A route or lazy import changed in App.tsx. Run:\n" +
        "  node scripts/routes/build-prefetch-map.mjs",
    );
    process.exit(1);
  }
  console.log(`route prefetch map is current: ${entries.length} route(s)`);
} else {
  fs.writeFileSync(OUT, serialised);
  console.log(`build-prefetch-map: ${entries.length} route(s) -> ${path.relative(ROOT, OUT)}`);
}
